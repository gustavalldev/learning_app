Практическое правило: индексировать нужно поля, которые реально участвуют в частых запросах. Для небольших справочников индекс может не дать заметной пользы. Для таблиц submissions, materials, assignments и course_students индексы полезны, потому что эти таблицы активно участвуют в сценариях приложения.

