1. Что такое избыточность данных

Избыточность возникает, когда одинаковые сведения повторяются в нескольких местах без необходимости. Например, если в каждой строке журнала хранить ФИО студента, название группы, название дисциплины, ФИО преподавателя и кафедру, то при изменении группы или кафедры придется обновлять много строк. Если часть строк обновили, а часть забыли, база начнет содержать противоречия.

Такие проблемы называют аномалиями. Аномалия обновления возникает, когда одно и то же значение нужно менять во многих местах. Аномалия вставки появляется, когда нельзя добавить данные об одной сущности без данных о другой. Например, нельзя создать дисциплину, пока нет студентов, если все хранится в одной таблице журнала. Аномалия удаления возникает, когда удаление одной записи случайно уничтожает важную информацию о другой сущности.

2. Первая нормальная форма

Первая нормальная форма требует, чтобы значения в ячейках были атомарными, то есть неделимыми с точки зрения базы данных. Нельзя хранить список дисциплин в одном текстовом поле студента: "Базы данных, Мобильная разработка, Проектирование". Такой список сложно фильтровать, связывать с заданиями и проверять внешними ключами.

Вместо этого создается отдельная таблица course_students, где каждая строка означает одно назначение студента на одну дисциплину. Если студент изучает три дисциплины, в таблице будет три строки. Это делает данные удобными для SQL-запросов и исключает ручной разбор строк.

3. Вторая нормальная форма

Вторая нормальная форма важна для таблиц с составным ключом. Она требует, чтобы неключевые поля зависели от всего ключа, а не только от его части. Например, в таблице course_students ключ может состоять из course_id и student_id. В такую таблицу не стоит добавлять full_name студента или title дисциплины. ФИО зависит только от student_id, а название дисциплины - только от course_id.

Правильнее хранить ФИО в users, данные студента в students, дисциплину в courses, а в course_students оставить только связь. Тогда изменение названия дисциплины выполняется в одном месте, а все связанные сценарии продолжают работать.

4. Третья нормальная форма

Третья нормальная форма требует, чтобы неключевые поля не зависели друг от друга транзитивно. Например, если в students хранить group_id, group_name и speciality, то speciality зависит не от студента напрямую, а от группы. Если направление подготовки изменится, придется обновлять всех студентов этой группы.

Лучшее решение - вынести группы в таблицу student_groups. Студент хранит group_id, а название группы, направление и курс хранятся в справочнике групп. В интерфейсе можно показать студенту название группы через JOIN, но физически данные не дублируются в каждой записи.

5. Пример нормализации учебного журнала

Ненормализованная таблица журнала могла бы содержать поля: student_name, group_name, course_title, assignment_title, question_text, answer_text, score, teacher_comment. Такая таблица быстро разрастается и повторяет одни и те же данные.

Нормализованная структура разделяет данные:

users хранит учетные записи;
student_groups хранит группы;
students связывает пользователя с группой;
courses хранит дисциплины;
